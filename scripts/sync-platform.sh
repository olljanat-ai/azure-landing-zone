#!/usr/bin/env bash
# Writes ./platform exactly like the ALZ IaC Accelerator (bootstrap module `alz_local`, starter module
# `platform_landing_zone`) does from ./accelerator/config, without creating any Azure resources:
#
#   - the starter module of Azure/alz-terraform-accelerator at $ACCELERATOR_REF (examples left out),
#     with the azurerm backend block enabled,
#   - accelerator/config/platform-landing-zone.tfvars as platform-landing-zone.auto.tfvars,
#   - accelerator/config/lib as lib/,
#   - terraform.tfvars.json with the bootstrap inputs the starter module needs.
#
# Use it to upgrade the starter module (bump ACCELERATOR_REF) and after every change in accelerator/config.
# CI runs it with --check and fails when ./platform differs from what the accelerator would generate.
set -euo pipefail

ACCELERATOR_REF="${ACCELERATOR_REF:-v17.6.0}"

root="$(cd "$(dirname "$0")/.." && pwd)"
config="$root/accelerator/config"
target="$root/platform"
check=false
[[ "${1:-}" == "--check" ]] && check=true

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
git clone -q --depth 1 --branch "$ACCELERATOR_REF" https://github.com/Azure/alz-terraform-accelerator.git "$tmp/src" 2>/dev/null

out="$tmp/out"
mkdir -p "$out"
(cd "$tmp/src/templates/platform_landing_zone" && tar --exclude='./examples' -cf - .) | (cd "$out" && tar -xf -)

# Same transformation as accelerator-bootstrap-modules/modules/file_manipulation (locals.files.tf)
sed -i 's|# backend "azurerm" {}|backend "azurerm" {}|' "$out/terraform.tf"

rm -rf "$out/lib"
cp -r "$config/lib" "$out/lib"
cp "$config/platform-landing-zone.tfvars" "$out/platform-landing-zone.auto.tfvars"

python3 -I - "$config/inputs.yaml" "$out/terraform.tfvars.json" <<'PY'
import json, sys
import yaml
inputs = yaml.safe_load(open(sys.argv[1]))
tfvars = {
    "root_parent_management_group_id": inputs.get("root_parent_management_group_id", ""),
    "subscription_ids": {k: v for k, v in inputs["subscription_ids"].items() if v},
}
with open(sys.argv[2], "w") as f:
    json.dump(tfvars, f, indent=2)
    f.write("\n")
PY

cat > "$out/ACCELERATOR.md" <<MD
# Generated by the ALZ IaC Accelerator – do not edit

This folder is the output of the [Azure Landing Zones IaC Accelerator](https://azure.github.io/Azure-Landing-Zones/accelerator/)
(starter module \`platform_landing_zone\` of Azure/alz-terraform-accelerator \`$ACCELERATOR_REF\`) for the inputs in
[\`accelerator/config\`](../accelerator/config). Change the inputs there and run \`scripts/sync-platform.sh\`.
MD

if $check; then
  if ! diff -r "$out" "$target" > "$tmp/diff"; then
    cat "$tmp/diff"
    echo "platform/ is out of date: run scripts/sync-platform.sh" >&2
    exit 1
  fi
  echo "platform/ matches accelerator/config ($ACCELERATOR_REF)"
else
  rm -rf "$target"
  cp -r "$out" "$target"
  echo "platform/ generated from accelerator/config ($ACCELERATOR_REF)"
fi
